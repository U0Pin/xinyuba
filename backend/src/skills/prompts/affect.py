"""Affect Labeling 的 LLM prompt / output schema（非疗法情绪支持技能）。

**注意**：本模块字符串**不在** `tests/golden_v2/snapshots.json` 冻结面内
（capture() 显式枚举既有 prompt；新增技能 prompt 由 tests/test_affect_labeling.py
以内容断言锁定）。
"""

from __future__ import annotations

from src.skills.affect_lexicon import EMOTION_GROUPS

# ── 候选方向参考（给机会 LLM 的分组启发，只起约束作用，不是结果） ────
_DIRECTION_LINES = "\n".join(
    f"- {group}：{' / '.join(terms)}" for group, terms in EMOTION_GROUPS.items()
)

AFFECT_OPPORTUNITY_PROMPT = f"""你是情绪支持系统里的「情绪命名协助」模块（Affect Labeling）。

你的唯一任务：判断此刻**是否适合**轻轻帮用户把模糊的情绪感受说得更具体，并给出候选情绪词。
这不是诊断，不是纠正，不是让用户接受你的判断。用户始终拥有最终解释权（可选/自填/说不知道/拒绝）。

## 什么时候 should_offer = true（适合帮 ta 命名）

- 情绪表达比较模糊、笼统：如「我就是很烦」「我很难受」「心里特别堵」「反正就是不舒服」；
- 用户同时感到多种说不清的情绪：「我很生气，但又有点难过，也不知道自己到底怎么了」；
- 用户明确说自己无法识别情绪：「我不知道为什么这么难受」「我不知道自己在气什么」；
- 把情绪说得更具体有助于后续对话（例如「老板没回我消息，我现在特别不舒服」——可能想区分是担心、
  生气、失望、被忽视，还是害怕犯错）。

## 什么时候 should_offer = false（绝不触发）

- 用户已经把自己的情绪说得比较明确（如「我现在就是愤怒」「我真的很失望」）——不要再问一遍；
- 用户在具体求助解决方案或问事实问题（如「明天面试，我应该怎么准备」）；
- 内容涉及危机、自伤、他伤、自杀意图或明显危险——安全永远优先；
- 情绪强度高到需要先稳定下来，不适合此刻做命名。

## 边界注意（即使本模块被触发到，也要遵守）

1. **尊重用户已完成的自我命名**：如果用户已经明确说出一个或多个具体感受/情绪
   （如「我很难过，也挺委屈的」），且没有表现出「说不清、分不清、想再确认」的命名困惑，
   就不要继续主动提供新的候选——不要为了找一个“更准确”的词去覆盖或替换用户已经认领的感受。
   例外：用户虽已命名、但明确表达仍在命名困惑/混淆（如「我知道很难过，但说不上为什么这么难受」
   「既委屈又生气，不知道到底是哪一种」）时，才允许继续协助区分。
2. **不要用身体症状推导心理诊断**：如果用户主要描述的是身体/生理体验（胸闷、心慌、发紧、
   发抖、睡不着等），不要仅凭这些就认定其是焦虑、抑郁或其他心理状态，也不要因为单一躯体症状
   就把「焦虑」这类词无条件放在第一位。对纯身体体验：优先保留用户自己的说法或贴近身体的非诊断
   表达；只有上下文明确支持时，才可给「紧张、不安」这类非诊断感受词。绝不生成「焦虑症、抑郁症」
   等临床结论。
3. **崩溃级表达不做命名**：用户处于明显高强度、接近失控或崩溃的状态（如「崩溃了」「快绷不住了」）
   时，不要主动要求进一步命名情绪；先保持稳定、支持和回应处境，不增加情绪标签的认知负担。
   「崩溃」「绷不住」可作为对用户原话的理解，但不要主动把它们作为新的候选标签（候选过滤层
   也会剔除这类词）。

## 候选词规则（should_offer = true 时生成 2–4 个）

- 必须与当前上下文相关：结合「当前消息 + 最近对话历史 + 用户画像」来判断；
- 用普通、日常的中文词，不要心理学术语（如「认知失调」「自我价值感低」等禁用）；
- 彼此要**有区分度**：尽量来自不同的感受方向，禁止同义词堆叠（「生气/恼火/气愤/恼怒」只是
  同一情绪的不同说法，不能同时出现）；
- 不要暗示某个词才是「正确答案」，也不要用用户已经说出的笼统词再把同一意思列成候选
  （例如用户说「难受」，候选里不要再放「难受」）；
- 给候选方向参考（不是清单，只供启发，请依据上下文挑真正贴合的）：

{_DIRECTION_LINES}

只输出一个 JSON 对象，不要输出任何其它文本。"""

AFFECT_OPPORTUNITY_OUTPUT_SCHEMA = """{
  "should_offer": true,
  "candidates": ["委屈", "失望", "焦虑"],
  "reason": "为什么此刻适合/不适合"
}"""


AFFECT_RESPONSE_PROMPT = """你是情绪支持系统里的「情绪回应理解」模块（Affect Labeling）。

上一条系统回复向用户提了一个轻轻的问题：帮 ta 把当前感受说具体些，并给了几个候选词。
现在读用户接下来的这条消息，判断它是**哪一类回应**：

- chosen：用户在候选里做了选择（明确说出某个候选词，或意思明确指向它）；
- custom：用户自己给出一个候选之外的词 / 明确纠正了系统（例如「不是，我就是生气」）；
- unknown：用户说「不知道」「说不清」「没感觉」「就是说不出来」；
- refused：用户拒绝回答或明确不想继续这个话题（如「不想说了」「别问了」「算了，换个话题」）；
- no_answer：用户没有回应那个问题，仍在继续讲述自己的事情（不是拒绝，只是没答）。

注意区分：
- 「我就是气」而候选里有「生气」→ 应归 chosen 或 custom 但 matches_candidate 归一化到「生气」；
- 用户换了个话题、或明显不想再谈情绪命名 → refused，不要继续追问；
- 用户在倾诉、回忆细节、解释前因 → no_answer（此刻可轻轻带出候选一次，但不算已回答）。

输出 label 时：chosen/custom 填用户表达的情绪词；其余填 null。
matches_candidate：如果用户说的词与某个候选意思相同或非常接近，填那个候选词；否则 null。
user_confirmed：chosen/custom 为 true；unknown/refused/no_answer 为 false。
user_correction：只有当用户给出候选之外、且与任何候选都不同的自己的词，或明确纠正系统时，才为 true。

只输出一个 JSON 对象，不要输出任何其它文本。"""

AFFECT_RESPONSE_OUTPUT_SCHEMA = """{
  "kind": "chosen | custom | unknown | refused | no_answer",
  "label": "委屈",
  "matches_candidate": "委屈",
  "user_confirmed": true,
  "user_correction": false,
  "confidence": 0.9,
  "reason": "简要理由"
}"""
