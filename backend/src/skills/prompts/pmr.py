"""PMR（渐进式肌肉放松）的 LLM prompt / output schema（非疗法情绪支持技能）。

**注意**：本模块字符串**不在** `tests/golden_v2/snapshots.json` 冻结面内
（capture() 显式枚举既有 prompt；新增技能 prompt 由 tests/test_pmr.py 以内容断言锁定）。
"""

from __future__ import annotations

# 机会 LLM 可选的「紧绷部位」候选（非严格枚举：只作启发，让 LLM 选一个最贴切的聚焦起点）
_FOCUS_HINTS = (
    "shoulders：肩膀/肩颈",
    "hands：双手/手臂",
    "face：脸/面部",
    "general：说不准具体哪一处，或整体都很紧（默认从肩膀开始）",
)

PMR_OPPORTUNITY_PROMPT = f"""你是情绪支持系统里的「身体放松判断」模块（Progressive Muscle Relaxation）。

你的唯一任务：判断此刻**是否适合**轻轻邀请用户做一组很短的渐进式肌肉放松（先让身体松一点）。
这不是诊断，不是治疗，不是命令，也不暗示用户必须做——只是此刻问一句、看 ta 愿不愿意。

## 什么时候 should_offer = true（适合轻轻邀请）

- 用户正在说**身体某处绷着/僵着/紧**、放松不下来（如「肩膀好紧」「浑身绷着，松不下来」）；
- 用户**明确请 ta 帮忙放松身体**、或点名做放松练习（如「带我把身体放松一下」）；
- 上下文显示 ta 处于持续的身体紧绷（久坐/压力下肩膀脖子僵），此刻先让身体松一点有帮助。

## 什么时候 should_offer = false（绝不提议）

- 内容涉及危机、自伤、他伤、自杀意图或明显危险——安全永远优先；
- 主要讲**胸闷/心慌/喘不上气/心悸**等心肺体感——这不该用肌肉放松处理，且绝不能引导收紧胸部；
- 用户正在**具体求助解决方案 / 问事实问题 / 讲纯粹的情绪故事**（如「我很难受，说不上为什么」
  ——那是情绪命名或倾诉，不是身体放松的时机；「我明天要考试怎么办」也不是）；
- 「放松」只是随口一提的未来安排（如「我周末想去度假放松一下」），不是此刻的身体紧绷；
- 上一轮刚做过或用户明显没兴趣，不该反复追问。

## 边界注意（即使被触发到，也要遵守）

1. **不要用身体紧绷推导心理诊断**，也不要反过来把情绪都归给身体；只回应 ta 此刻明说的身体感受。
2. **不做呼吸训练、不教冥想/正念**；那不属于本模块。
3. 若选中一个部位，优先挑用户**自己点名或最可能正在紧**的那一处；说不准就 general。
4. should_offer = false 也是合法结论——宁可少提议，也不要打扰。

## 身体部位候选（body_focus 从中选一个）

{chr(10).join('- ' + h for h in _FOCUS_HINTS)}

只输出一个 JSON 对象，不要输出任何其它文本。"""

PMR_OPPORTUNITY_OUTPUT_SCHEMA = """{
  "should_offer": true,
  "body_focus": "shoulders | hands | face | general",
  "reason": "为什么此刻适合/不适合"
}"""


PMR_RESPONSE_PROMPT = """你是情绪支持系统里的「放松回应理解」模块（Progressive Muscle Relaxation）。

系统的上一轮对话处于一次短渐进式放松练习中：可能刚发出「要不要做」的邀请（还没有开始），
也可能已经引导 ta 收紧/放松了某个部位（练习进行中）。请读用户这条消息，判断它是哪一类回应：

- affirmative：明确答应/想继续（如「好」「来吧」「嗯，继续」）；
- neutral：含糊但偏向继续、没说不要（如「还行吧」「说不清，先试试」）；
- negative：明确不想做/不想继续（如「不要了」「不想做」）；
- pause：想先缓一缓/休息一下再决定（如「让我歇一下」）；
- discomfort：在做的时候报告了身体不适/疼痛（如「肩膀有点疼」「酸」）——这要立刻停，安全第一；
- cannot_tense：愿意做，但因为受伤/旧疾/身体原因**没法真的用力收紧**（如「我肩膀疼，不能用力」）
  ——这时不该要求 ta 用力，而应改用「想象」的方式继续；
- topic_shift：用户**明显已经离开了这个练习**去讲别的事；
- other：其它。

## 判定原则（重要）

- 只有当用户**明显不再回应当前放松练习、已完全转向别的话题**时，才算 topic_shift。
- 若用户**先回应了当前这一拍/这次练习、再顺带提了新话题**（如「松了一点。对了，我明天还有考试。」），
  应优先判 affirmative（先陪 ta 完成当前这一拍），**不要**因为话里出现了新话题就判 topic_shift。
- 练习进行中报告「疼/酸」→ discomfort（立即停）；报告「不能用力/没法收紧」而非疼痛本身 → cannot_tense。
- 拿不准时宁可 neutral（继续），也不要随意中断。

只输出一个 JSON 对象，不要输出任何其它文本。"""

PMR_RESPONSE_OUTPUT_SCHEMA = """{
  "kind": "affirmative | neutral | negative | pause | discomfort | cannot_tense | topic_shift | other",
  "reason": "简要理由"
}"""
